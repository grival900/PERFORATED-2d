"""Exports the pygame game's balance numbers, Level 1 layout and texts into GDScript.

Run from the repo root:  python 2D-lab/tools/export_to_godot.py
Writes 2D-lab/perforated-godot/scripts/cfg.gd and tr.gd.  Re-run it after changing
2D-lab/game/settings.py, level.py or strings.py and the Godot port picks the new numbers up.
(Needs pygame-ce installed only because level.py imports pygame; no window is opened.)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, "game")
OUT = os.path.join(ROOT, "perforated-godot", "scripts")
sys.path.insert(0, GAME)
os.environ.setdefault("SDL_VIDEODRIVER", "dummy")

import level as L  # noqa: E402
import settings as S  # noqa: E402
import strings as ST  # noqa: E402

VEC2 = {"PLAYER_START", "ALTAR_POS"}
VEC2_LIST = {"SPAWN_POINTS", "HEART_SPOTS", "PILLARS", "BRAZIERS"}
RECT_LIST = {"LOW_WALLS"}


def gd(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(round(v, 6))
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(v, (list, tuple, set)):
        return "[" + ", ".join(gd(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{gd(k)}: {gd(x)}" for k, x in v.items()) + "}"
    raise TypeError(type(v))


def emit(name, value):
    if name in VEC2:
        return f"const {name} = Vector2({value[0]}, {value[1]})"
    if name in VEC2_LIST:
        return f"const {name} = [" + ", ".join(f"Vector2({x}, {y})" for x, y in value) + "]"
    if name in RECT_LIST:
        return f"const {name} = [" + ", ".join(f"Rect2({x}, {y}, {w}, {h})" for x, y, w, h in value) + "]"
    return f"const {name} = {gd(value)}"


SCALARS = """SCREEN_W SCREEN_H ARENA WALL GATE_X0 GATE_X1 PLAYER_START PLAYER_RADIUS PLAYER_SPEED PLAYER_ACCEL
PLAYER_FRICTION PLAYER_MAX_HP PLAYER_HP_CAP INVULN_TIME DASH_SPEED DASH_TIME DASH_IFRAMES DASH_CHARGES
DASH_CHARGES_CAP DASH_RECHARGE DASH_DAMAGE SHOT_COOLDOWN SHOT_SPEED SHOT_DAMAGE SHOT_PIERCE SHOT_LIFE SHOT_RANGE
SHOT_SPREAD_DEG SHOT_MAX_COUNT HALO_ORBS HALO_RADIUS HALO_SPEED HALO_DAMAGE HALO_HIT_GAP PULSE_COOLDOWN
PULSE_RADIUS PULSE_DAMAGE ARC_COOLDOWN ARC_RANGE ARC_JUMPS ARC_JUMP_RANGE ARC_DAMAGE STAT_DAMAGE_STEP STAT_RATE_STEP
STAT_RATE_FLOOR STAT_AREA_STEP STAT_BONUS_CAP STAT_PIERCE_CAP STAGE_SECONDS NUM_STAGES ENEMIES MELEE_KINDS
BULWARK_ENRAGE MAX_ENEMIES SPEAR_SPEED SPEAR_COOLDOWN SPEAR_WINDUP SPEAR_LIFE ELITE_CHARGE_COOLDOWN ELITE_WINDUP
ELITE_CHARGE_SPEED ELITE_CHARGE_TIME LUNGE_RANGE LUNGE_WINDUP LUNGE_SPEED LUNGE_TIME LUNGE_COOLDOWN RECYCLE_DISTANCE
STAGE_HP STAGE_SPEED STAGES SWARM_PACK LANCER_CAP ELITES_AT_STAGE SPAWN_DIST MIN_SPAWN_DISTANCE SPAWN_POINTS
STAGE_AT_PTS PRIDE_MAX BAR_EDGES BOX_START BOX_TARGET BOX_RESPAWN BOX_RESPAWN_MIN_DIST BOX_GILDED_CHANCE
BOX_CRATE_GEMS BOX_GILDED_GEMS GEM_MAGNET GEM_SPEED GEM_LIFE HEART_SPOTS HEART_RESPAWN ALTAR_POS SPAWN_AFTER_EXIT""".split()


def main():
    os.makedirs(OUT, exist_ok=True)
    lines = ["# GENERATED by 2D-lab/tools/export_to_godot.py from game/settings.py and game/level.py. Do not edit by hand.",
             "@tool", "class_name Cfg", "extends RefCounted", ""]
    for n in SCALARS:
        v = getattr(S, n)
        if n == "ENEMIES":     # drop what the Godot port does not use
            v = {k: {a: b for a, b in st.items() if a in ("hp", "speed", "r", "pts", "sprite", "shadow", "knock")}
                 for k, st in v.items() if k in ("sentinel", "skirmisher", "lancer", "swarmer", "bulwark", "elite")}
        if n == "STAGES":
            v = {k: dict(st) for k, st in v.items()}
        lines.append(emit(n, v))
    c1 = S.LEVEL1
    for name, val in (("FAN_STAGE", c1.fan_stage), ("ELITE_RAGE_STAGE", c1.elite_rage_stage),
                      ("NOVA_MARKS", c1.nova_marks), ("NOVA_SPEARS", c1.nova_spears), ("AMBIENT", S.THEMES[1]["ambient"])):
        lines.append(emit(name, val))
    lay = L.LAYOUTS[1]
    lines.append(emit("PILLARS", lay["pillars"]))
    lines.append(emit("PILLAR_HALF", L.PILLAR_HALF))
    lines.append(emit("LOW_WALLS", lay["low_walls"]))
    lines.append(emit("BRAZIERS", lay["braziers"]))
    lines += ["", "static func upgrade_cost(n: int) -> int:",
              f"\treturn {S.upgrade_cost(0)} + 25 * n + 8 * n * n", ""]
    open(os.path.join(OUT, "cfg.gd"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))

    keep = lambda k: not (k[-1] in "23" or k in ("next_level",))
    text = {lang: {k: v for k, v in d.items() if keep(k)} for lang, d in ST.TEXT.items()}
    tr = ["# GENERATED by 2D-lab/tools/export_to_godot.py from game/strings.py. Do not edit by hand.",
          "class_name Tr", "extends RefCounted", "", "const TEXT = " + gd(text), "",
          "static func t(lang: String, key: String):", "\treturn TEXT[lang][key]", ""]
    open(os.path.join(OUT, "tr.gd"), "w", encoding="utf-8", newline="\n").write("\n".join(tr))
    print("PRIDE_MAX", S.PRIDE_MAX, "stage points", [round(x) for x in S.STAGE_AT_PTS])


if __name__ == "__main__":
    main()
